// BROWSER DOWNLOAD TRIGGER
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Trigger a browser file download using a temporary Blob URL.
 *
 * How it works:
 *   1. Create a Blob from the string content
 *   2. Generate a temporary object URL pointing at that Blob
 *   3. Programmatically click a synthetic <a> element with the 'download' attribute
 *   4. Immediately revoke the object URL to free memory
 *
 * The anchor must be attached to the DOM briefly for Firefox compatibility.
 *
 * @param {string} content  - The file content as a string
 * @param {string} filename - Suggested name for the downloaded file (e.g. "export.sh")
 * @param {string} mimeType - MIME type for the Blob (e.g. "text/x-shellscript")
 */
export function triggerDownload(
  content: string,
  filename: string,
  mimeType: string,
): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);

  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  anchor.style.display = 'none';

  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);

  // Free the temporary URL immediately — the download is already queued
  URL.revokeObjectURL(url);
}

/**
 * Build the suggested download filename for a script, including today's date.
 *
 * @param {'unix' | 'windows'} os - Target operating system
 * @returns {string} e.g. "export-music-2026-07-29.sh" or "export-music-2026-07-29.bat"
 *
 * @example
 *   getScriptFilename('unix')    // → "export-music-2026-07-29.sh"
 *   getScriptFilename('windows') // → "export-music-2026-07-29.bat"
 */
export function getScriptFilename(os: 'unix' | 'windows'): string {
  const date = new Date().toISOString().split('T')[0]; // "YYYY-MM-DD"
  const ext = os === 'unix' ? 'sh' : 'bat';
  return `export-music-${date}.${ext}`;
}

