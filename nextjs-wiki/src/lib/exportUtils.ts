/**
 * Escape a string for safe embedding in a bash single-quoted context.
 *
 * Bash single-quoted strings are literal — the only character that needs
 * special handling is a literal single-quote, which ends the current
 * single-quoted string, inserts an escaped single-quote, then reopens it.
 *
 * @example
 *   shellEscape('/path/with spaces/file.mp3') // → "'/path/with spaces/file.mp3'"
 *   shellEscape("/it's/here.mp3")             // → "'/it'\\''s/here.mp3'"
 *
 * @param {string} value - The raw value to escape
 * @returns {string} A bash-safe single-quoted representation
 */
function shellEscape(value: string): string {
  return `'${value.replace(/'/g, "'\\''")}'`;
}

/** Convert slash-separated playlist paths to native Windows separators. */
function normalizeBatchPath(value: string): string {
  const normalized = value.replace(/\//g, '\\');
  return /^[A-Za-z]:$/.test(normalized) ? `${normalized}\\` : normalized;
}

/** PowerShell's -EncodedCommand expects the command as Base64-encoded UTF-16LE. */
function encodePowerShellCommand(command: string): string {
  let binary = '';
  for (let index = 0; index < command.length; index++) {
    const codeUnit = command.charCodeAt(index);
    binary += String.fromCharCode(codeUnit & 0xff, codeUnit >>> 8);
  }
  return btoa(binary);
}
